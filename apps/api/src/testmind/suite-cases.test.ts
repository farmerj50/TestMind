import test from "node:test";
import assert from "node:assert/strict";
import { hasSuiteCases, parseSuiteCases } from "./suite-cases.js";

// Verbatim copy of a real B4-generated spec (Bes, qe/contacts.qe.spec.ts, plan cmwuauvn7...).
const B4_CONTACTS_SPEC = `// Generated by TestMind B4 from plan cmwuauvn700017k3skbu5liit (2026-11-24T06:14:29.946Z). Each test maps to a B3 scenario via [qe:<id>].
import { qe, expect, traceScenario, onPath } from './fixtures';
import { ContactsPage } from './pages/contacts.page';

qe.describe("/contacts (signed-out visitor)", () => {
  qe("Anonymous access to /contacts is denied (lands on /) [qe:31173381cd8b]", async ({ page }) => {
    traceScenario("31173381cd8b", []);
    await page.goto("/contacts", { waitUntil: 'domcontentloaded' });
    // Objective: A signed-out visitor requesting /contacts must not reach its content; observed behavior: requested /contacts, landed on /
    await expect(page).not.toHaveURL(onPath("^/contacts\\\\/?$"), { timeout: 10_000 });
    await expect(page).toHaveURL(onPath("^\\\\/?$"));
  });
});
`;

// Excerpt of a real existing generated spec (Bes, login.spec.ts) using plain test()/test.step().
const EXISTING_LOGIN_SPEC = `import { Locator, Page, TestInfo, test, expect } from '@playwright/test';
// Auto-generated for page /login 2 test(s)

test("Page loads: /login", async ({ page }, testInfo: TestInfo) => {
  test.info().annotations.push({ type: "parentSuite", description: "Testmind Generated Suite" });
  await test.step("1. Navigate to https://www.bes-app.com/login", async () => {
    await navigateTo(page, "/login");
  });
  await expect(page).toHaveURL(pathRegex("/login"), { timeout: 15000 });
});

test('Form submits – /login', async ({ page }) => {
  await page.getByRole('button', { name: /sign in/i }).click();
});
`;

test("a real B4-generated spec yields its actual test, scenario ID, objective, actions and assertions", () => {
  const cases = parseSuiteCases("Bes/qe/contacts.qe.spec.ts", B4_CONTACTS_SPEC);
  assert.equal(cases.length, 1, "qe(...) is a Playwright test; qe.describe and traceScenario(...) are not");
  const [c] = cases;
  assert.equal(c.title, "Anonymous access to /contacts is denied (lands on /) [qe:31173381cd8b]");
  assert.equal(c.line, 6);
  assert.equal(c.scenarioId, "31173381cd8b");
  assert.match(c.objective ?? "", /^A signed-out visitor requesting \/contacts must not reach its content/);
  assert.deepEqual(c.steps?.map((s) => [s.line, s.kind]), [[8, "action"], [9, "objective"], [10, "assertion"], [11, "assertion"]]);
  assert.equal(c.steps?.[0].text, `await page.goto("/contacts", { waitUntil: 'domcontentloaded' });`);
  assert.match(c.steps?.[2].text ?? "", /not\.toHaveURL\(onPath\(/, "the real locator/assertion text is shown, not a summary");
  assert.equal(hasSuiteCases("contacts.qe.spec.ts", B4_CONTACTS_SPEC), true, "the GET-time coercion must never rewrite this file");
});

test("an existing test()-based spec keeps the same cases, now with its real steps", () => {
  const cases = parseSuiteCases("Bes/login.spec.ts", EXISTING_LOGIN_SPEC);
  assert.deepEqual(cases.map((c) => [c.title, c.line]), [["Page loads: /login", 4], ["Form submits – /login", 12]]);
  assert.equal(cases[0].scenarioId, undefined);
  assert.deepEqual(cases[0].steps?.map((s) => s.kind), ["action", "action", "assertion"]);
  assert.match(cases[1].steps?.[0].text ?? "", /getByRole\('button'/);
});

test("imported helpers called with a string are never mistaken for tests", () => {
  const src = `import { qe, traceScenario, step } from './fixtures';\ntraceScenario("abc", []);\nstep("not a test", () => {});\nqe.skip("Skipped scenario [qe:x1]", async ({ page }) => {\n  await page.goto('/');\n});\n`;
  assert.deepEqual(parseSuiteCases("a.spec.ts", src).map((c) => c.title), ["Skipped scenario [qe:x1]"]);
  assert.equal(parseSuiteCases("plain.spec.ts", "const x = 1;\n").length, 0);
});

test("feature files are unchanged", () => {
  assert.deepEqual(parseSuiteCases("login.feature", "Feature: Login\n  Scenario: Sign in works\n"), [{ title: "Sign in works", line: 2 }]);
});
