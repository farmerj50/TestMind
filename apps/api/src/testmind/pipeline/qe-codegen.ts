// B4: Autonomous test-suite generation from a persisted B3 plan.
//
// Writes into the project's existing generated suite (so Suites lists them and the existing
// runner executes them) under qe/:
//   qe/fixtures.ts            shared fixtures: isolated signed-in session from approved credentials
//   qe/pages/<route>.page.ts  one Page Object per route, built ONLY from observed labels/types
//   qe/<route>.qe.spec.ts     one spec per route; every test titled "<scenario> [qe:<id>]" and
//                             annotated with its scenario + acceptance criteria
//   qe/qe-manifest.json       scenario -> file/test mapping
//
// Rules: each test asserts its scenario's OBJECTIVE (not just "page loaded"); a scenario without
// a deterministic, evidence-backed assertion is reported as not generated - never fabricated;
// credentials are only ever referenced as environment-variable NAMES, never values.
import type { ApplicationModelPage, ApplicationModelStore } from "../../lib/application-model.js";
import type { PlanScenario, QePlan } from "../../lib/qe-plan.js";

export type GeneratedFile = { path: string; content: string };
export type GeneratedTest = { scenarioId: string; title: string; testTitle: string; file: string; kind: PlanScenario["kind"]; criteria: PlanScenario["criteria"]; requiresAuth: boolean };
export type NotGenerated = { scenarioId: string; title: string; reason: string };
export type QeCodegenResult = { files: GeneratedFile[]; tests: GeneratedTest[]; notGenerated: NotGenerated[] };

export const QE_AUTH_ENV = { email: "TM_QE_AUTH_EMAIL", password: "TM_QE_AUTH_PASSWORD", loginPath: "TM_QE_LOGIN_PATH" } as const;

const J = (v: unknown) => JSON.stringify(v);
const SUBMIT_RE = /\b(continue|submit|send|save|register|sign ?up|create account|create|next|confirm|log ?in|sign ?in|reset)\b/i;
const TOGGLE_RE = /^(sign ?in|create account|log ?in|sign ?up)$/i;

export function routeSlug(route: string) {
  return route === "/" ? "home" : route.replace(/^\/+|\/+$/g, "").replace(/[^a-zA-Z0-9]+/g, "-").toLowerCase() || "home";
}
const className = (route: string) => routeSlug(route).split("-").map((w) => w[0]?.toUpperCase() + w.slice(1)).join("") + "Page";
const routeRegex = (route: string) => (route === "/" ? "^\\/?$" : `^${route.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\/?$`);
/** Generated-code helper name: matches a URL's pathname (toHaveURL(RegExp) would match the full URL). */
const ON_PATH_HELPER = `/** Route assertions compare the pathname only (query strings and origin are not part of a route). */
export const onPath = (pattern: string) => (url: URL) => new RegExp(pattern).test(url.pathname);
`;
export const qeTestTitle = (s: Pick<PlanScenario, "title" | "id">) => `${s.title} [qe:${s.id}]`;

/** The observed submit action for a page: a button whose label reads as submit, preferring non-toggle labels. */
export function submitLabelFor(page?: ApplicationModelPage): string | null {
  const actions = page?.observed?.actions ?? [];
  return actions.find((a) => SUBMIT_RE.test(a) && !TOGGLE_RE.test(a.trim())) ?? actions.find((a) => SUBMIT_RE.test(a)) ?? null;
}

function pageObject(route: string, page?: ApplicationModelPage): string {
  const submit = submitLabelFor(page);
  return `// Generated by TestMind B4 from observations of ${route} (${page?.observed?.observedAt ?? page?.lastSeenAt ?? "unknown"}). Do not hand-edit; regenerate.
import type { Page, Locator } from '@playwright/test';

export class ${className(route)} {
  static readonly path = ${J(route)};
  /** Labels the crawler actually observed on this page. */
  static readonly observedActions: readonly string[] = ${J(page?.observed?.actions ?? [])};
  static readonly observedFields: readonly string[] = ${J(page?.observed?.fields ?? [])};

  constructor(readonly page: Page) {}

  async goto() {
    await this.page.goto(${className(route)}.path, { waitUntil: 'domcontentloaded' });
  }

  /** An observed action by its visible label (real button, or an element exposing that text). */
  action(label: string): Locator {
    return this.page.getByRole('button', { name: label }).or(this.page.getByRole('link', { name: label })).or(this.page.getByText(label, { exact: true })).first();
  }

  /** An observed field by label, placeholder, or (for typed inputs) its input type. */
  field(label: string): Locator {
    const typed = ['email', 'password', 'tel', 'number', 'date', 'search', 'url'].includes(label) ? this.page.locator(\`input[type="\${label}"]\`) : this.page.getByLabel(label, { exact: false });
    return typed.or(this.page.getByPlaceholder(label, { exact: false })).first();
  }

  emailInput(): Locator { return this.page.locator('input[type="email"]').first(); }
  passwordInput(): Locator { return this.page.locator('input[type="password"]').first(); }

  /** The submit control observed on this page${submit ? ` ("${submit.replace(/[*/]/g, "")}")` : ""}. */
  submit(): Locator {
    ${submit ? `return this.action(${J(submit)});` : `return this.page.locator('button[type="submit"], input[type="submit"]').first();`}
  }

  /** Any visible feedback a validation failure would show (role=alert or error wording). */
  feedback(): Locator {
    return this.page.getByRole('alert').or(this.page.getByText(/invalid|valid email|required|error|must|incorrect|please enter/i)).first();
  }
}
`;
}

function fixtures(): string {
  return `// Generated by TestMind B4. Shared fixtures for autonomous QE specs.
//
// Credentials are NEVER written here: they are read at runtime from ${QE_AUTH_ENV.email} /
// ${QE_AUTH_ENV.password}, which the runner sets for this run only from approved, encrypted
// project secrets. Sign-in happens once per worker in a SEPARATE browser that the test runner does
// not trace, screenshot, or record, and only its resulting storage state is reused - in fresh,
// isolated contexts - by tests that explicitly require authentication.
import { test as base, expect, chromium, type BrowserContext, type Page } from '@playwright/test';

type AuthState = Awaited<ReturnType<BrowserContext['storageState']>>;

export const qe = base.extend<{ authPage: Page }, { qeAuthState: AuthState | null }>({
  qeAuthState: [async ({}, use) => {
    const email = process.env.${QE_AUTH_ENV.email};
    const password = process.env.${QE_AUTH_ENV.password};
    if (!email || !password) { await use(null); return; }
    const baseURL = process.env.PW_BASE_URL || process.env.TM_BASE_URL;
    const browser = await chromium.launch();
    try {
      const ctx = await browser.newContext({ baseURL });
      const page = await ctx.newPage();
      await page.goto(process.env.${QE_AUTH_ENV.loginPath} || '/login', { waitUntil: 'domcontentloaded' });
      await page.locator('input[type="email"]').or(page.getByLabel(/email|username/i)).first().fill(email);
      await page.locator('input[type="password"]').first().fill(password);
      await page.getByRole('button', { name: /sign.?in|log.?in|continue|submit/i }).first().click();
      await page.waitForURL((u) => !/\\/(login|signin|sign-in)(\\/|$)/i.test(new URL(u.toString()).pathname), { timeout: 30_000 });
      await use(await ctx.storageState());
    } finally {
      await browser.close();
    }
  }, { scope: 'worker' }],

  authPage: async ({ browser, qeAuthState }, use, testInfo) => {
    // Without approved credentials an authenticated scenario is skipped (reported, never passed).
    testInfo.skip(!qeAuthState, 'No approved test credentials for this run');
    const baseURL = process.env.PW_BASE_URL || process.env.TM_BASE_URL;
    const ctx = await browser.newContext({ baseURL, storageState: qeAuthState! });
    const page = await ctx.newPage();
    await use(page);
    await ctx.close();
  },
});

export { expect };

${ON_PATH_HELPER}
/** Links a test to its B3 scenario and acceptance criteria in the report. */
export function traceScenario(scenarioId: string, criteria: Array<{ storyKey: string; criterionId: string }> = []) {
  qe.info().annotations.push({ type: 'qe-scenario', description: scenarioId });
  for (const c of criteria) qe.info().annotations.push({ type: 'acceptance-criterion', description: \`\${c.storyKey}/\${c.criterionId}\` });
}
`;
}

type Body = { code: string; requiresAuth?: boolean } | { skip: string };

/** The assertion body for a scenario - or the reason no honest assertion can be generated. */
function bodyFor(s: PlanScenario, store: ApplicationModelStore, hasCredentials: boolean): Body {
  const page = store.pages[s.route];
  const po = className(s.route);
  switch (s.kind) {
    case "access_denied": {
      const final = page?.access?.finalRoute;
      return { code: `    await page.goto(${J(s.route)}, { waitUntil: 'domcontentloaded' });
    // Objective: ${s.objective}
    await expect(page).not.toHaveURL(onPath(${J(routeRegex(s.route))}), { timeout: 10_000 });${final ? `\n    await expect(page).toHaveURL(onPath(${J(routeRegex(final))}));` : ""}` };
    }
    case "auth_access":
      if (!hasCredentials) return { skip: "Requires approved test credentials - none were provided for this run" };
      return { requiresAuth: true, code: `    await authPage.goto(${J(s.route)}, { waitUntil: 'domcontentloaded' });
    // Objective: a signed-in user reaches ${s.route} instead of being sent away (signed-out visitors land elsewhere).
    await expect(authPage).toHaveURL(onPath(${J(routeRegex(s.route))}), { timeout: 15_000 });` };
    case "password_masked":
      return { code: `    const po = new ${po}(page);
    await po.goto();
    await expect(po.passwordInput()).toBeVisible();
    await expect(po.passwordInput()).toHaveAttribute('type', 'password');` };
    case "https_only":
      return { code: `    const po = new ${po}(page);
    await po.goto();
    expect(page.url(), 'page carrying credentials must be served over HTTPS').toMatch(/^https:\\/\\//);
    const insecureActions = await page.locator('form[action]').evaluateAll((forms) => forms.map((f) => f.getAttribute('action') ?? '').filter((a) => a.startsWith('http:')));
    expect(insecureActions, 'no form may post credentials over plain HTTP').toEqual([]);` };
    case "invalid_email": {
      if (!page) return { skip: `No observations of ${s.route}` };
      return { code: `    const po = new ${po}(page);
    await po.goto();
    await po.emailInput().fill('not-an-email');
    await po.submit().click();
    // Objective: ${s.objective}
    await expect(page, 'the form must not complete').toHaveURL(onPath(${J(routeRegex(s.route))}));
    // Email-specific: the email input itself must be invalid, or the page must say so about the email.
    const emailInvalid = await po.emailInput().evaluate((el) => !(el as HTMLInputElement).checkValidity());
    const emailFeedback = await page.getByRole('alert').filter({ hasText: /email/i }).or(page.getByText(/(invalid|valid|enter a|incorrect|check).{0,25}email|email.{0,30}(invalid|valid|required|format)/i)).first().isVisible().catch(() => false);
    expect(emailInvalid || emailFeedback, 'the malformed email must be rejected').toBe(true);` };
    }
    case "required_empty": {
      if (!page) return { skip: `No observations of ${s.route}` };
      return { code: `    const po = new ${po}(page);
    await po.goto();
    await po.submit().click();
    // Objective: ${s.objective}
    await expect(page, 'the form must not complete').toHaveURL(onPath(${J(routeRegex(s.route))}));
    const nativelyInvalid = await page.locator('input:invalid').count();
    const feedbackShown = await po.feedback().isVisible().catch(() => false);
    expect(nativelyInvalid > 0 || feedbackShown, 'the rejection must be indicated to the user').toBe(true);` };
    }
    case "pattern":
      return { skip: "Pattern violations need a known invalid value for the specific pattern - not generated automatically" };
    case "xss_reflection": {
      const fields = (page?.observed?.fields ?? []).filter((f) => f !== "password");
      if (!fields.length) return { skip: "No observed text inputs" };
      return { code: `    const po = new ${po}(page);
    await po.goto();
    const payload = '"><img src=x data-qe-probe=1 onerror="window.__qeProbe=1"><script>window.__qeProbe=1</script>';
    for (const label of ${J(fields)}) await po.field(label).fill(payload).catch(() => {});
    await po.submit().click().catch(() => {});
    await page.waitForTimeout(1500);
    // Objective: ${s.objective}
    expect(await page.evaluate(() => (window as any).__qeProbe ?? null), 'injected script must not execute').toBeNull();
    await expect(page.locator('img[data-qe-probe]'), 'injected markup must not be rendered').toHaveCount(0);` };
    }
    case "navigate":
      if (!s.target) return { skip: "Workflow target route unknown" };
      return { code: `    const po = new ${po}(page);
    await po.goto();
    await page.locator(${J(`a[href$="${s.target}"]`)}).first().click();
    await expect(page).toHaveURL(onPath(${J(routeRegex(s.target))}));` };
    case "api_ok": {
      const [method, path] = s.title.split(" ");
      const pathRe = `^${path.replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/:id/g, "[^/]+")}$`;
      return { code: `    const response = page.waitForResponse((r) => r.request().method() === ${J(method)} && new RegExp(${J(pathRe)}).test(new URL(r.url()).pathname), { timeout: 20_000 });
    await page.goto(${J(s.route)}, { waitUntil: 'domcontentloaded' });
    // Objective: ${s.objective}
    expect((await response).status()).toBeLessThan(400);` };
    }
    case "criterion":
      return criterionBody(s, store);
    case "existing_case":
    case "reverify":
      return { skip: "Executed by its existing test" };
    default:
      return { skip: "No generation template for this scenario" };
  }
}

/**
 * Acceptance criteria: only what the criterion text and its OBSERVED evidence support.
 *  - "shows X" (positive): each matched observed element is visible on the evidence page.
 *  - invalid/error (negative) on an observed email field: the rejection template.
 *  - "reachable from <page>" (workflow): clicking the matched observed action on the first
 *    evidence page leads to one of the other evidence pages.
 * Anything else is reported, not guessed.
 */
function criterionBody(s: PlanScenario, store: ApplicationModelStore): Body {
  const ev = s.evidence.filter((e) => e.source === "crawl").map((e) => {
    const [route, rest] = e.detail.split(": ");
    return { route, matched: (rest ?? "").split(", ").filter(Boolean) };
  }).filter((e) => store.pages[e.route]);
  if (!ev.length) return { skip: "No observed evidence page for this criterion" };
  const primary = ev[0];
  const po = className(primary.route);
  const text = s.objective;
  if (s.category === "negative" && /\bemail\b/i.test(text) && primary.matched.some((m) => /email/i.test(m))) {
    return bodyFor({ ...s, kind: "invalid_email", route: primary.route }, store, false);
  }
  if (s.category === "workflow") {
    const action = primary.matched.find((m) => (store.pages[primary.route]?.observed?.actions ?? []).includes(m));
    const targets = ev.slice(1).map((e) => e.route).filter((r) => r !== primary.route);
    if (!action || !targets.length) return { skip: "The criterion's start action or destination page was not observed" };
    return { code: `    const po = new ${po}(page);
    await po.goto();
    await po.action(${J(action)}).click();
    // Objective (acceptance criterion): ${text}
    await expect(page).toHaveURL(onPath(${J(targets.map(routeRegex).join("|"))}), { timeout: 15_000 });` };
  }
  if (s.category === "positive") {
    const p = store.pages[primary.route];
    const fields = primary.matched.filter((m) => (p?.observed?.fields ?? []).includes(m));
    const actions = primary.matched.filter((m) => (p?.observed?.actions ?? []).includes(m));
    if (!fields.length && !actions.length) return { skip: "Matched terms are not concrete observed elements" };
    return { code: `    const po = new ${po}(page);
    await po.goto();
    // Objective (acceptance criterion): ${text}
${fields.map((f) => `    await expect(po.field(${J(f)}), ${J(`${f} field`)}).toBeVisible();`).join("\n")}${fields.length && actions.length ? "\n" : ""}${actions.map((a) => `    await expect(po.action(${J(a)}), ${J(`${a} action`)}).toBeVisible();`).join("\n")}` };
  }
  return { skip: "No deterministic assertion can be derived for this criterion's wording - not fabricated" };
}

export function generateQeSuite(plan: QePlan, store: ApplicationModelStore, opts: { hasCredentials: boolean }): QeCodegenResult {
  const tests: GeneratedTest[] = [];
  const notGenerated: NotGenerated[] = [];
  const byRoute = new Map<string, Array<{ s: PlanScenario; code: string; requiresAuth: boolean }>>();

  for (const s of plan.scenarios) {
    if (s.kind === "existing_case" || s.kind === "reverify") continue; // already executable
    if (s.status === "blocked_unverifiable") { notGenerated.push({ scenarioId: s.id, title: s.title, reason: s.blockedReason ?? "unverifiable" }); continue; }
    if (s.status === "blocked_auth" && !opts.hasCredentials) { notGenerated.push({ scenarioId: s.id, title: s.title, reason: s.blockedReason ?? "requires authentication" }); continue; }
    const body = bodyFor(s, store, opts.hasCredentials);
    if ("skip" in body) { notGenerated.push({ scenarioId: s.id, title: s.title, reason: body.skip }); continue; }
    const fileRoute = s.kind === "criterion" ? (s.evidence.find((e) => e.source === "crawl")?.detail.split(": ")[0] ?? s.route) : s.route;
    byRoute.set(fileRoute, [...(byRoute.get(fileRoute) ?? []), { s, code: body.code, requiresAuth: !!body.requiresAuth }]);
  }

  const files: GeneratedFile[] = [{ path: "qe/fixtures.ts", content: fixtures() }];
  const usedRoutes = new Set<string>();
  for (const [route, entries] of [...byRoute.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    const file = `qe/${routeSlug(route)}.qe.spec.ts`;
    const poRoutes = new Set<string>([route]);
    for (const e of entries) for (const m of e.code.matchAll(/new (\w+Page)\(/g)) if (m[1] !== className(route)) {
      const r = Object.keys(store.pages).find((k) => className(k) === m[1]);
      if (r) poRoutes.add(r);
    }
    poRoutes.forEach((r) => usedRoutes.add(r));
    const anon = entries.filter((e) => !e.requiresAuth);
    const auth = entries.filter((e) => e.requiresAuth);
    const render = (e: (typeof entries)[number], fixture: string) => {
      const title = qeTestTitle(e.s);
      tests.push({ scenarioId: e.s.id, title: e.s.title, testTitle: title, file, kind: e.s.kind, criteria: e.s.criteria, requiresAuth: e.requiresAuth });
      return `  qe(${J(title)}, async ({ ${fixture} }) => {
    traceScenario(${J(e.s.id)}, ${J(e.s.criteria.map((c) => ({ storyKey: c.storyKey, criterionId: c.criterionId })))});
${e.code}
  });`;
    };
    const content = `// Generated by TestMind B4 from plan ${plan.jobId} (${plan.createdAt}). Each test maps to a B3 scenario via [qe:<id>].
import { qe, expect, traceScenario, onPath } from './fixtures';
${[...poRoutes].sort().map((r) => `import { ${className(r)} } from './pages/${routeSlug(r)}.page';`).join("\n")}

${anon.length ? `qe.describe(${J(`${route} (signed-out visitor)`)}, () => {
${anon.map((e) => render(e, "page")).join("\n\n")}
});` : ""}
${auth.length ? `
qe.describe(${J(`${route} (signed-in user)`)}, () => {
  // Signed-in sessions carry auth cookies: never record traces/videos for these tests.
  qe.use({ trace: 'off', video: 'off' });
${auth.map((e) => render(e, "authPage")).join("\n\n")}
});` : ""}
`;
    files.push({ path: file, content });
  }
  for (const r of [...usedRoutes].sort()) files.push({ path: `qe/pages/${routeSlug(r)}.page.ts`, content: pageObject(r, store.pages[r]) });
  files.push({ path: "qe/qe-manifest.json", content: JSON.stringify({ planJobId: plan.jobId, generatedFrom: plan.createdAt, tests, notGenerated }, null, 2) });
  return { files, tests, notGenerated };
}
