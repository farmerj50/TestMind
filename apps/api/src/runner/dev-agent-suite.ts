import fs from "node:fs";
import path from "node:path";
import { DEFAULT_FRAMEWORK_ID } from "@testmind/core/framework";
import { generatedSpecDir } from "../lib/generatedSpecs.js";
import { TEST_FILE_PATTERN } from "./dev-agent-objective.js";

// Generated Dev Agent tests are project artifacts: saved to the project's Suites storage
// ("Generated (playwright-ts)") as soon as they are generated - before execution - so they stay
// viewable and rerunnable from Suites whether they pass or fail, without needing a PR. The saved
// file is the latest revision; every revision (original + repairs) stays in the run's iteration
// history. The Git worktree is untouched by this.

export const SUITE_FOLDER = "autonomous-dev";

type RunScope = { id: string; projectId: string; requestedBy: string; instructionText?: string | null };

/** Header on the Suites copy only (not the Git change): which run produced it and its original objective. */
export function suiteHeader(run: RunScope): string {
  const objective = (run.instructionText ?? "").replace(/\s+/g, " ").trim().slice(0, 500);
  return [`// Generated by TestMind Autonomous Dev (run ${run.id}).`, ...(objective ? [`// Objective: ${objective}`] : []), ""].join("\n");
}

/** Folder inside the project's generated suite, relative to the project root shown in Suites. */
export const suiteRelDir = (runId: string) => `${SUITE_FOLDER}/${runId}`;

export function suiteDirForRun(run: RunScope, root?: string): string {
  return path.join(generatedSpecDir({ adapterId: DEFAULT_FRAMEWORK_ID, userId: run.requestedBy, projectId: run.projectId }, root), SUITE_FOLDER, run.id);
}

/** Writes generated test files (with content) to Suites; returns their Suites-relative paths. */
export function saveGeneratedSpecsToSuite(run: RunScope, files: Array<{ path: string; content?: string }>, root?: string): string[] {
  const dir = path.resolve(suiteDirForRun(run, root));
  const saved: string[] = [];
  for (const f of files) {
    const rel = f.path.replace(/\\/g, "/").replace(/^\.?\/+/, "");
    if (typeof f.content !== "string" || !TEST_FILE_PATTERN.test(rel)) continue;
    const abs = path.resolve(dir, rel);
    if (!abs.startsWith(dir + path.sep)) continue; // never outside this run's suite folder
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, `${suiteHeader(run)}${f.content}`, "utf8");
    saved.push(`${suiteRelDir(run.id)}/${rel}`);
  }
  return saved;
}

export type TestOutcome = { title: string; file: string | null; status: "passed" | "failed" | "skipped" };

const OUTCOME_LINE = /^\s*(✓|✔|ok|✘|×|x|-)\s+\d+\s+(?:\[[^\]]+\]\s+›\s+)?(.+?)(?:\s+\(\d+(?:\.\d+)?m?s\))?\s*$/;

/** Individual test results from Playwright's list reporter output. */
export function parseTestOutcomes(output: string | null | undefined): TestOutcome[] {
  const out: TestOutcome[] = [];
  for (const raw of String(output ?? "").replace(/\u001b\[[0-9;]*[A-Za-z]/g, "").split(/\r?\n/)) {
    const m = OUTCOME_LINE.exec(raw);
    if (!m || !m[2].includes("›")) continue;
    const parts = m[2].split("›").map((s) => s.trim());
    const fileMatch = /^(.+?\.(?:spec|test)\.[cm]?[jt]sx?)(?::\d+(?::\d+)?)?$/.exec(parts[0]);
    const status = /^(✓|✔|ok)$/.test(m[1]) ? "passed" : m[1] === "-" ? "skipped" : "failed";
    out.push({ title: parts.slice(fileMatch ? 1 : 0).join(" › "), file: fileMatch ? fileMatch[1].replace(/\\/g, "/") : null, status });
  }
  return out;
}
